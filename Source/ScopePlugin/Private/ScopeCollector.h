#pragma once
#include "ScopeTypes.h"

// Static helpers that collect scene data from the editor world.
// nDisplay is accessed via UE reflection — no hard dependency on DisplayCluster plugin.
class FScopeCollector
{
public:
    // ── Original five collectors ─────────────────────────────────────────────
    static FScopeCameraData   CollectCamera();
    static FScopeTrackingData CollectTracking();
    static FScopeICVFXData    CollectICVFX();
    static FScopeNDisplayData CollectNDisplay();
    static FScopeSceneData    CollectScene();

    // ── Extended data layer collectors ───────────────────────────────────────
    // Iterates all valid AActor instances in the editor world.
    static TArray<FScopeActorEntry>  CollectAllActors();

    // Iterates only AStaticMeshActor instances.
    static TArray<FScopeActorEntry>  CollectStaticMeshes();

    // Iterates all light actor types and captures photometric data.
    static TArray<FScopeLightEntry>  CollectAllLights();

    // Iterates AActor instances whose class was generated by a Blueprint.
    static TArray<FScopeActorEntry>  CollectBlueprints();

    // Returns playback state of the first ALevelSequenceActor found.
    static FScopeSequencerData       CollectSequencer();

    // Returns HDRI/cubemap state of the first ASkyLight found.
    static FScopeHDRIData            CollectHDRI();

    // Returns transform data for actors whose names are in ActorNames.
    static TArray<FScopeActorEntry>  CollectSelectedActors(const TSet<FString>& ActorNames);
};
